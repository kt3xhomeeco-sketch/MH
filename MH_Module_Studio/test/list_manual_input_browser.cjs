const {chromium}=require(process.env.MH_PLAYWRIGHT||'playwright');
const fs=require('fs'),path=require('path'),assert=require('assert');
(async()=>{
 const root=path.resolve(__dirname,'..'),folder=path.join(root,'outputs/list-071');
 const read=name=>JSON.parse(fs.readFileSync(path.join(folder,name+'.json'),'utf8'));
 const browser=await chromium.launch({headless:true,executablePath:process.env.MH_BROWSER||undefined});
 try{
  const page=await browser.newPage({viewport:{width:1400,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{window.sent=[];window.sketchup={request:raw=>window.sent.push(JSON.parse(raw))};});
  await page.goto('file:///'+path.join(root,'ui/parametric.html').replaceAll('\\','/'));
  await page.evaluate(state=>window.receive(state),read('preset'));
  const selector=page.locator('[data-variable-id="input:hghe0m3ihb"] select[data-field="value"]');
  assert(await selector.locator('option[value="=hsxpei34m2"]').isEnabled());
  await selector.selectOption('=hsxpei34m2');
  const source=page.locator('[data-variable-id="input:hsxpei34m2"] input[data-field="value"]');
  assert(await source.isEditable());await source.fill('473.25');
  await page.locator('#save-variables').click();
  const packet=await page.evaluate(()=>sent.at(-1));
  assert.equal(packet.variables.find(row=>row.binding==='hghe0m3ihb').formula,'hsxpei34m2');
  assert.equal(packet.variables.find(row=>row.binding==='hsxpei34m2').value,473.25);
  await page.evaluate(state=>window.receive(state),read('manual'));
  assert.equal(await selector.inputValue(),'=hsxpei34m2');
  await selector.selectOption('450');await page.locator('#save-variables').click();
  assert.equal((await page.evaluate(()=>sent.at(-1))).variables.find(row=>row.binding==='hghe0m3ihb').formula,'');
  await page.goto('file:///'+path.join(root,'ui/module_options.html').replaceAll('\\','/'));
  await page.setViewportSize({width:320,height:285});
  await page.evaluate(state=>window.receive(state),read('preset-options'));
  const dropdown=page.locator('select[data-variable-id="input:hghe0m3ihb"]');
  assert.equal(await page.locator('.manual-value').count(),0);
  await dropdown.selectOption('=hsxpei34m2');
  assert.equal((await page.evaluate(()=>sent.at(-1))).value,'=hsxpei34m2');
  await page.evaluate(state=>window.receive(state),read('manual-options'));
  const manual=page.locator('.manual-value');assert.equal(await manual.inputValue(),'473.25');
  await manual.fill('486.5');await manual.press('Enter');
  const request=await page.evaluate(()=>sent.at(-1));
  assert.equal(request.variable_id,'input:hsxpei34m2');assert.equal(request.value,486.5);
  const ack=read('manual-options');ack.token='next';ack.rows[0].manual_input.value=486.5;ack.rows[0].value=486.5;
  await page.evaluate(()=>window.keptManual=document.querySelector('.manual-value'));
  await page.evaluate(state=>window.receive(state),ack);
  assert(await page.evaluate(()=>keptManual===document.querySelector('.manual-value')));
  assert.equal(await dropdown.inputValue(),'=hsxpei34m2');
  assert(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)));
  await page.screenshot({path:path.join(folder,'compact.png')});
  await dropdown.selectOption('500');assert.equal((await page.evaluate(()=>sent.at(-1))).value,500);
  await page.evaluate(state=>window.receive(state),read('preset-options'));
  assert.equal(await page.locator('.manual-value').count(),0);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(folder,'browser.json'),JSON.stringify({ok:true,errors}));
  console.log('Actual drawer: Parametric manual/preset switching, hidden inline input, compact auto apply and stable acknowledgement passed.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
