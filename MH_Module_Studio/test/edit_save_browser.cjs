// Browser checks for names, assembly presentation and responsive option structure changes.
const {chromium}=require(process.env.MH_PLAYWRIGHT||'playwright');
const path=require('path'),assert=require('assert'),fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.MH_BROWSER||undefined});
 try{
  const root=path.resolve(__dirname,'..'),page=await browser.newPage({viewport:{width:1240,height:850}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{window.sent=[];window.sketchup={request:raw=>sent.push(JSON.parse(raw))};});
  await page.goto('file:///'+path.join(root,'ui/parametric.html').replaceAll('\\','/'));
  const source=JSON.parse(fs.readFileSync(path.join(root,'outputs/rules-att-ui-state.json'),'utf8'));
  await page.evaluate(s=>receive(s),source);
  const title=page.locator('#module-title'),name=page.locator('[data-part-name]').first();
  await title.fill('Tủ tên mới');await title.blur();
  assert.deepEqual(await page.evaluate(()=>sent.at(-1)),{action:'rename_model',name:'Tủ tên mới',part_key:null,rule_id:source.rule.id,snapshot_id:source.snapshots.at(-1).id,revision:source.parametric_revision||0});
  const renamed=structuredClone(source);renamed.module_name='Tủ tên mới';renamed.parametric_revision=(source.parametric_revision||0)+1;
  await page.evaluate(s=>receive(s),renamed);
  await name.fill('Giằng mới');await name.blur();
  const detail=await page.evaluate(()=>sent.at(-1));assert.equal(detail.action,'rename_model');assert.equal(detail.part_key,source.parametric_sheet.parts[0].key);assert.equal(detail.name,'Giằng mới');
  const ack=structuredClone(renamed);ack.parametric_revision++;ack.parametric_sheet.parts[0].name='Giằng mới';
  await page.evaluate(s=>receive(s),ack);
  assert.equal(await name.inputValue(),'Giằng mới');
  await page.locator('[data-field="symbol"]').first().fill('T1moi');
  assert(await title.isEnabled());assert(await name.isEnabled());
  await title.fill('Tủ có bản nhập biến');await title.blur();
  const dirtyRename=structuredClone(ack);dirtyRename.module_name='Tủ có bản nhập biến';dirtyRename.parametric_revision++;
  await page.evaluate(s=>receive(s),dirtyRename);
  assert.equal(await page.locator('[data-field="symbol"]').first().inputValue(),'T1moi');
  assert.equal(await page.evaluate(()=>dirty),true);
  await page.locator('#save-skp').click();
  const saved=await page.evaluate(()=>sent.at(-1));assert.equal(saved.action,'save_skp');assert.equal(saved.variables[0].symbol,'T1moi');
  await page.evaluate(s=>receive({...s,error:true,message:'Đã hủy lưu.'}),dirtyRename);
  assert.equal(await page.locator('[data-field="symbol"]').first().inputValue(),'T1moi');
  await page.locator('#revert-variables').click();
  // A single Save click commits the active name first, then saves once on acknowledgement.
  await name.fill('Tên vừa nhập');await page.locator('#save-skp').click();
  assert.equal(await page.evaluate(()=>sent.at(-1).action),'rename_model');
  const clickAck=structuredClone(dirtyRename);clickAck.parametric_revision++;clickAck.parametric_sheet.parts[0].name='Tên vừa nhập';
  const sentBefore=await page.evaluate(()=>sent.length);
  await page.evaluate(s=>receive(s),clickAck);
  await page.waitForFunction(()=>sent.at(-1).action==='save_skp');
  assert.equal(await page.evaluate(()=>sent.length),sentBefore+1);
  assert.equal(await page.evaluate(()=>sent.at(-1).revision),clickAck.parametric_revision);
  await page.evaluate(s=>receive({...s,message:'Đã hủy lưu.'}),clickAck);
  assert(await name.isEnabled());assert(await page.locator('#save-skp').isEnabled());
  await name.fill('');await name.blur();
  await page.locator('#save-skp').click();
  const errorBefore=await page.evaluate(()=>sent.length);
  await page.evaluate(s=>receive({...s,error:true,message:'Tên cần từ 1 đến 120 ký tự.'}),clickAck);
  assert.equal(await page.evaluate(()=>sent.length),errorBefore);
  assert(await name.isEnabled());assert(await title.isEnabled());assert(await page.locator('#save-skp').isEnabled());
  const assembly={snapshots:[{id:'assembly-snapshot',label:'Cụm tủ'}],module_name:'Cụm tủ',rule:null,parametric_revision:1,parametric_sheet:{assembly:true,variables:[],attributes:[],categories:{},parts:[{key:'member-1',name:'Khung',values:[600,600,800,0,0,0],expressions:[],formulas:Array(6).fill('')}]}};
  await page.evaluate(s=>receive(s),assembly);
  assert(await page.locator('#save-skp').isEnabled());
  for(const id of ['save-variables','add-variable','preview','trial','update'])assert(await page.locator('#'+id).isDisabled());
  await page.locator('.part-cell').first().dblclick();assert.equal(await page.locator('.cell-editor').count(),0);
  await page.locator('[data-part-name]').fill('Khung mới');await page.locator('[data-part-name]').blur();
  assert.deepEqual(await page.evaluate(()=>sent.at(-1)),{action:'rename_model',name:'Khung mới',part_key:'member-1',rule_id:null,snapshot_id:'assembly-snapshot',revision:1});
  await page.evaluate(s=>receive(s),assembly);await page.locator('#save-skp').click();assert.equal(await page.evaluate(()=>sent.at(-1).action),'save_skp');
  const hostile=structuredClone(source);hostile.parametric_sheet.parts[0].name='<img src=x onerror="window.bad=1">';hostile.module_name='<script>bad=1</script>';
  await page.evaluate(s=>receive(s),hostile);assert.equal(await page.locator('img').count(),0);assert.equal(await page.evaluate(()=>Boolean(window.bad)),false);
  await page.screenshot({path:path.join(root,'outputs/parametric-names-047.png')});
  await page.goto('file:///'+path.join(root,'ui/module_options.html').replaceAll('\\','/'));
  const options={root_pid:'one',token:'1',name:'Tủ',rows:[{id:'T1',name:'Độ dày',value:18.6,editable:true,category:'dimension',unit:'mm'}]};
  await page.evaluate(s=>receive(s),options);
  const input=page.locator('input');await input.fill('');await input.pressSequentially('2');
  await page.evaluate(()=>{const input=document.querySelector('input');input.setSelectionRange(1,1);});
  const expanded=structuredClone(options);expanded.token='2';expanded.rows.push({id:'T2',name:'Hậu',value:8,editable:true,category:'dimension',unit:'mm'});
  await page.evaluate(s=>receive(s),expanded);
  assert(await page.evaluate(()=>document.activeElement.dataset.variableId==='T1'&&document.activeElement.selectionStart===1));
  assert.equal(await page.locator('[data-variable-id="T1"]').inputValue(),'2');
  await page.locator('[data-variable-id="T1"]').press('Escape');
  await page.evaluate(s=>receive(s),expanded);
  await page.locator('#save-skp').click();assert.deepEqual(await page.evaluate(()=>sent.at(-1)),{action:'save_skp',root_pid:'one'});
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(root,'outputs/browser-047.json'),JSON.stringify({ok:true,errors},null,2));
  console.log('Parametric names, guarded drafts, assembly save UI, injection and Options focus across structure changes passed.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
