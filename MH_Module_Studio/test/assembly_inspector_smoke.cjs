// Developer-only browser verification. MH_PLAYWRIGHT may point to a bundled runtime.
const {chromium}=require(process.env.MH_PLAYWRIGHT||'playwright');
const path=require('path'),assert=require('assert'),fs=require('fs');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.MH_BROWSER||undefined});
  try{
    const page=await browser.newPage({viewport:{width:360,height:850}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.addInitScript(()=>{window.sent=[];window.sketchup={assembly_request:raw=>window.sent.push(JSON.parse(raw)),request:raw=>window.sent.push(JSON.parse(raw))};});
    const root=path.resolve(__dirname,'..');
    await page.goto('file:///'+path.join(root,'ui/assembly.html').replaceAll('\\','/'));
    const state={record:{mode:'contact',gap:3,count:2,angle:90,direction:'right',equal:false,ends:true,a:{name:'A / Hông trái'},b:{name:'B / Hông trái'}},gap:3,complete:true,picking:null,links:[]};
    await page.evaluate(s=>window.receiveAssembly(s),state);
    assert(await page.locator('#auto-links').isVisible(),'Selection inference is visible without opening a section');
    assert((await page.locator('#auto-links').boundingBox()).y<200,'Selection inference is near the top');
    const legend=await page.locator('body').textContent();assert(legend.includes('Shift + Click: phủ bì module')&&legend.includes('Ctrl + Click: phủ bì cụm'));
    assert(await page.locator('#pick-c').isHidden());
    const saved=structuredClone(state);saved.record.id='scope:link';
    await page.evaluate(s=>window.receiveAssembly(s),saved);
    assert((await page.locator('#hint').textContent()).includes('Bấm Gộp'));
    saved.links=[{...saved.record,a:{name:'Tủ / Hông',module_name:'Tủ'},b:{name:'Cánh / Mặt trong',module_name:'Cánh'}}];
    saved.link_groups=[{id:'pair',modules:[{name:'Tủ'},{name:'Cánh'}],links:[{...saved.links[0],label:'Khoảng cách · 3 mm'}]}];
    await page.evaluate(s=>window.receiveAssembly(s),saved);
    assert.deepEqual(await page.locator('#links .linked-module').allTextContents(),['Tủ','Cánh']);
    assert.equal(await page.locator('#links .link').textContent(),'Khoảng cách · 3 mm');
    assert(await page.locator('#links .linked-module').first().evaluate(element=>element.getBoundingClientRect().top<element.closest('section').querySelector('.link').getBoundingClientRect().top));
    await page.locator('#group').click();assert.equal(await page.evaluate(()=>window.sent.at(-1).action),'group');
    await page.locator('#module-names summary').click();
    await page.locator('#rename-a').fill('Tủ mới');await page.locator('#rename-a').blur();
    assert.deepEqual(await page.evaluate(()=>window.sent.at(-1)),{action:'rename',value:['a','Tủ mới']});
    assert(!(await page.locator('body').textContent()).includes('XYZ'));
    await page.locator('#gap').fill('5');await page.locator('#gap').blur();
    assert.deepEqual(await page.evaluate(()=>window.sent.at(-1)),{action:'value',value:['gap',5]});
    await page.locator('#bound').click();assert.equal(await page.evaluate(()=>window.sent.at(-1).action),'bound');
    await page.locator('#auto summary').click();
    await page.locator('#auto-gap').fill('12');
    await page.locator('#auto-links').click();assert.deepEqual(await page.evaluate(()=>window.sent.at(-1)),{action:'auto_links',value:12});
    await page.evaluate(s=>window.receiveAssembly({...s,notice:'Đã tạo 2 liên kết theo hiện trạng.'}),saved);
    assert((await page.locator('#status').textContent()).includes('Đã tạo 2'));
    assert(await page.locator('#saved').getAttribute('open')!==null);
    const grouped=structuredClone(saved);
    grouped.link_groups=[{id:'scope:group',name:'Cụm tủ',modules:[{name:'Tủ'},{name:'Cánh'},{name:'Nẹp'}],links:[{id:'touch',label:'Tiếp xúc · 0 mm'},{id:'front',label:'Đồng phẳng · 0 mm'}]}];
    await page.evaluate(s=>window.receiveAssembly(s),grouped);
    assert.deepEqual(await page.locator('#links .linked-module').allTextContents(),['Tủ','Cánh','Nẹp']);
    assert.equal(await page.locator('#links .group-name').textContent(),'Cụm tủ');
    await page.locator('#links .link').last().click();
    assert.deepEqual(await page.evaluate(()=>window.sent.at(-1)),{action:'load',value:'front'});
    const fit=structuredClone(state);fit.record.mode='fit';fit.record.c={name:'A / Hông phải'};
    await page.evaluate(s=>window.receiveAssembly(s),fit);
    assert(await page.locator('#pick-c').isVisible());assert(await page.locator('#fit-size').isChecked());
    await page.locator('#fit-size').uncheck();assert.deepEqual(await page.evaluate(()=>window.sent.at(-1)),{action:'fit_size',value:false});
    const repeat=structuredClone(state);repeat.record.mode='repeat';repeat.record.equal=true;repeat.gap=186.5;
    await page.evaluate(s=>window.receiveAssembly(s),repeat);
    assert.equal(await page.locator('#gap').inputValue(),'186.5');assert(await page.locator('#gap').getAttribute('readonly')!==null);
    await page.locator('[data-direction="down"]').click();assert.deepEqual(await page.evaluate(()=>window.sent.at(-1)),{action:'direction',value:'down'});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);assert(!overflow);
    await page.screenshot({path:path.join(root,'outputs/assembly-029/inspector.png'),fullPage:true});
    await page.goto('file:///'+path.join(root,'ui/parametric.html').replaceAll('\\','/'));
    const parametric=JSON.parse(fs.readFileSync(path.join(root,'outputs/rules-att-ui-state.json'),'utf8'));
    await page.evaluate(s=>window.receive(s),parametric);
    const placeholder=structuredClone(parametric);placeholder.module_name='Trạng thái 1';
    await page.evaluate(s=>window.receive(s),placeholder);
    await page.locator('#module-title').focus();
    const recovered=structuredClone(parametric);recovered.module_name='Khung Nóc Lọt';
    await page.evaluate(s=>window.receive(s),recovered);
    assert.equal(await page.locator('#module-title').inputValue(),'Khung Nóc Lọt','A pristine focused placeholder recovers its source title');
    await page.locator('#module-title').fill('Tên đang nhập');
    await page.evaluate(s=>window.receive(s),recovered);
    assert.equal(await page.locator('#module-title').inputValue(),'Tên đang nhập','A real title draft is retained');
    await page.locator('#module-title').evaluate(input=>{input.value='Khung Nóc Lọt';input.blur();});
    await page.evaluate(s=>window.receive(s),recovered);
    const symbol=page.locator('#variables-table [data-field="symbol"]').first();await symbol.fill('NewThickness');
    await page.locator('#save-skp').click();
    const save=await page.evaluate(()=>window.sent.at(-1));
    assert.equal(save.action,'save_skp');assert.equal(save.variables[0].symbol,'NewThickness');
    await page.evaluate(()=>window.receive({snapshots:[],rule:null,parametric_sheet:null,parametric_revision:0}));
    await page.locator('#capture-sketchup').click();assert.equal(await page.evaluate(()=>window.sent.at(-1).action),'capture_parametric');
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('Assembly inspector fields, opposing-face fit, directions, automatic gaps, layout and Parametric Read SketchUp passed.');
    fs.writeFileSync(path.join(root,'outputs/assembly-029/browser-check.json'),JSON.stringify({ok:true,errors},null,2));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
